"""FAQ and User Guide page for SyncForge."""

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QWidget, QVBoxLayout, QLabel, QScrollArea, QFrame
)
from syncforge.i18n.translations import tr


class FaqPage(QWidget):
    """Rich interactive help, guide and documentation page."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self._init_ui()

    def _init_ui(self):
        layout = QVBoxLayout(self)
        layout.setContentsMargins(28, 28, 28, 28)
        layout.setSpacing(14)

        header = QLabel(tr("faq"))
        header.setStyleSheet("font-size: 24px; font-weight: bold; color: #5865f2;")
        layout.addWidget(header)

        sub_header = QLabel("Довідник користувача, конфігурація правил та стандарти безпеки даних SyncForge")
        sub_header.setStyleSheet("color: #949ba4; font-size: 14px; margin-bottom: 6px;")
        layout.addWidget(sub_header)

        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.NoFrame)

        container = QWidget()
        c_layout = QVBoxLayout(container)
        c_layout.setSpacing(16)
        c_layout.setContentsMargins(0, 0, 10, 0)

        def add_faq_card(icon: str, title: str, html_content: str):
            card = QFrame()
            card.setProperty("class", "Card")
            card_layout = QVBoxLayout(card)
            card_layout.setContentsMargins(18, 16, 18, 16)
            card_layout.setSpacing(10)

            title_lbl = QLabel(f"{icon} {title}")
            title_lbl.setStyleSheet("font-size: 16px; font-weight: bold; color: #5865f2;")
            card_layout.addWidget(title_lbl)

            desc_lbl = QLabel(html_content)
            desc_lbl.setWordWrap(True)
            desc_lbl.setTextFormat(Qt.RichText)
            desc_lbl.setStyleSheet("font-size: 13px; line-height: 1.5;")
            card_layout.addWidget(desc_lbl)

            c_layout.addWidget(card)

        # 1. Modes
        add_faq_card(
            "🔄",
            "Режими синхронізації та їхнє призначення",
            """
            <p>SyncForge пропонує три фундаментальні режими синхронізації, розроблені за принципом <b>Zero Data Loss</b>:</p>
            <ul>
                <li><b>Режим A: Безпечне одностороннє оновлення (One-Way Safe)</b><br/>
                Копіює нові та змінені файли з ПК на цільовий диск. <b>Ніколи не видаляє сторонні чи раніше створені файли на цілі</b>. 
                Якщо файл видалено на ПК, на зовнішньому диску він залишається в цілості. Опціонально зберігає попередні версії файлів перед оновленням.</li>
                <br/>
                <li><b>Режим B: Безпечна двостороння синхронізація (Safe Bidirectional)</b><br/>
                Призначений для паралельної роботи на ПК та зовнішньому робочому SSD за допомогою базового стану (baseline).<br/>
                • Файл змінено тільки на ПК ➔ копіюється на SSD.<br/>
                • Файл змінено тільки на SSD ➔ копіюється на ПК.<br/>
                • Новий файл з будь-якого боку ➔ додається на іншу сторону.<br/>
                • Видалення на одному боці ➔ захищає і не затирає копію на іншому.<br/>
                • Файл незалежно змінено з обох сторін ➔ фіксується <b>Конфлікт</b> для вашого рішення.</li>
                <br/>
                <li><b>Режим C: Версійний холодний бекап (Versioned Cold Backup)</b><br/>
                Ідеально для резервних HDD-накопичувачів. Створює структуровані каталоги версій з датою і часом (наприклад, <code>v20261010_120000</code>). 
                Ніколи не змінює робочі файли на ПК, створює маніфести копіювання та підтримує перевірку контрольних сум BLAKE3.</li>
            </ul>
            """
        )

        # 2. Rules
        add_faq_card(
            "⚙️",
            "Правила фільтрації та маршрутизації (Rules Engine)",
            """
            <p>Правила дозволяють гнучко налаштовувати, які файли включати у синхронізацію, які пропускати, та куди саме їх зберігати:</p>
            <ul>
                <li><b>Виключити за маскою (EXCLUDE_GLOB)</b>: файли чи каталоги за шаблоном пропускаються під час аналізу.<br/>
                <i>Приклади:</i> <code>*.tmp</code>, <code>*.log</code>, <code>node_modules/*</code>, <code>.git/*</code>, <code>__pycache__/*</code>, <code>Thumbs.db</code>.</li>
                <br/>
                <li><b>Включити тільки за маскою (INCLUDE_GLOB)</b>: аналізуються та синхронізуються <i>виключно</i> файли, що збігаються з маскою.<br/>
                <i>Приклади:</i> <code>*.docx</code>, <code>*.pdf</code>, <code>*.cpp</code>, <code>*.rs</code>.</li>
                <br/>
                <li><b>Максимальний розмір (MAX_SIZE)</b>: запобігає переповненню накопичувача надвеликими файлами.<br/>
                <i>Приклади шаблону:</i> <code>500M</code>, <code>2G</code>, <code>100M</code>. Файли більші за ліміт буде пропущено.</li>
                <br/>
                <li><b>Мінімальний розмір (MIN_SIZE)</b>: відсікає нульові або крихітні системні файли.<br/>
                <i>Приклади шаблону:</i> <code>1K</code>, <code>4K</code>.</li>
                <br/>
                <li><b>Маршрутизація (ROUTE)</b>: перенаправляє файли у специфічні підпапки на цільовому диску.<br/>
                <i>Приклад:</i> Шаблон <code>*.pdf</code> з підпапкою призначення <code>Documents/PDF/</code> збереже всі знайдені PDF-файли за цим маршрутом.</li>
                <br/>
                <li><b>Пріоритет (Priority)</b>: число від 0 до 1000+. Що вищий пріоритет, то раніше перевіряється правило. Наприклад, виключення <code>*.tmp</code> з пріоритетом 100 спрацює раніше за загальне правило включення.</li>
            </ul>
            <p><b>Швидке редагування:</b> Ви можете змінювати тип правила через випадаючий список та вмикати/вимикати правило прапорцем безпосередньо в таблиці Правил!</p>
            """
        )

        # 3. Preview and Overrides
        add_faq_card(
            "👁️",
            "Попередній перегляд, ручне керування діями та пауза/зупинка",
            """
            <p>SyncForge забезпечує повний контроль перед будь-якою зміною файлів на диску:</p>
            <ul>
                <li><b>Найновіші файли зверху</b>: Таблиця попереднього перегляду автоматично сортує файли за часом останньої зміни — найсвіжіші файли завжди видно першими.</li>
                <li><b>Кнопка Паузи / Зупинки</b>: Під час тривалої синхронізації ви можете будь-якої миті призупинити передачу (Пауза) або безпечно перервати її (Зупинити).</li>
                <li><b>Випадаючий список дії в кожному рядку</b>: Ви можете вручну змінити дію для будь-якого файлу:
                    <ul>
                        <li><code>КОПІЮВАТИ</code> / <code>ОНОВИТИ</code> — передати файл;</li>
                        <li><code>ПРОПУСТИТИ</code> — пропустити файл у цій сесії;</li>
                        <li><code>ЗАХИЩЕНО ВІД ВИДАЛЕННЯ</code> — захистити цільовий файл від змін.</li>
                    </ul>
                </li>
                <li><b>Перемикання профілів прямо в перегляді</b>: У верхній панелі вкладки "Попередній перегляд" є випадаючий список профілів та кнопка швидкого повторного аналізу <b>🔄 Оновити аналіз</b>.</li>
                <li><b>Автоматичне оновлення після виконання</b>: Після завершення копіювання система миттєво переоцінює стан дисків — успішно синхронізовані файли автоматично переходять у статус актуальних.</li>
            </ul>
            """
        )

        # 4. Device Enrollment and Hardware Protection
        add_faq_card(
            "🛡️",
            "Реєстрація дисків та апаратний захист від випадкового запису",
            """
            <p>У системі Windows літери дисків (C:, D:, E:, F:) не є постійними та можуть непередбачувано змінюватися при підключенні нових флешок або зовнішніх SSD.</p>
            <p>Для захисту від випадкового перезапису чужого накопичувача SyncForge використовує комплексну апаратну ідентифікацію:</p>
            <ul>
                <li><b>Volume GUID</b> — системний глобальний ідентифікатор тому Windows.</li>
                <li><b>Серійний номер тому</b> — апаратний номер розділу диска.</li>
                <li><b>Маркер безпеки <code>.syncforge_id.json</code></b> — персистентний криптографічний маркер, що записується в корінь накопичувача під час реєстрації.</li>
            </ul>
            <p>Якщо зареєстрований SSD не підключено або під його літерою з'явився інший пристрій, синхронізація <b>буде безпечно зупинена</b> з попередженням, гарантуючи збереження ваших даних.</p>
            """
        )

        # 5. Conflicts Resolution
        add_faq_card(
            "⚔️",
            "Вирішення конфліктів файлів",
            """
            <p>Конфлікт виникає в Режимі B, якщо файл було одночасно змінено на ПК і на SSD після попередньої синхронізації.</p>
            <p>У вкладці <b>Конфлікти</b> ви маєте змогу обрати один із 4 варіантів:</p>
            <ul>
                <li><b>Залишити версію ПК</b> — перезаписує файл на SSD свіжою локальною копією.</li>
                <li><b>Залишити версію SSD</b> — оновлює файл на ПК версією із зовнішнього диска.</li>
                <li><b>Зберегти обидві</b> — найбезпечніший варіант: зберігає обидва варіанти файлів, додаючи маркер до імені.</li>
                <li><b>Пропустити</b> — відкладає рішення без зміни жодного файлу.</li>
            </ul>
            """
        )

        # 6. Deletion policies, tombstones, and staleness protection
        add_faq_card(
            "🗑️",
            "Обробка видалених файлів, Tombstones та захист плану від застарівання",
            """
            <p>SyncForge забезпечує абсолютну безпеку збереження даних (Zero Data Loss) та дає зручні інструменти для роботи з видаленими файлами:</p>
            <ul>
                <li><b>Чому файл лишається на SSD, якщо його видалено на ПК?</b><br/>
                За замовчуванням увімкнено захист від видалення (PRESERVE_ALL). SyncForge ніколи автоматично не стирає ваші файли, щоб випадкове видалення на комп'ютері не призвело до безповоротної втрати копії на диску.</li>
                <br/>
                <li><b>Які варіанти дій доступні в Попередньому перегляді для таких файлів?</b>
                    <ul>
                        <li><b>Залишити тільки на SSD</b> — створює Tombstone у базі даних, запам'ятовуючи вибір, і при наступних аналізах файл автоматично вважається актуальним (SKIP).</li>
                        <li><b>Відновити на ПК із SSD</b> — копіює збережену копію з зовнішнього накопичувача назад на комп'ютер.</li>
                        <li><b>Архівувати копію на SSD</b> — переміщує файл у захищену службову папку <code>.syncforge_archive/</code> з позначкою часу.</li>
                        <li><b>Видалити також із SSD</b> — видаляє файл на накопичувачі тільки після вашого явного окремого підтвердження!</li>
                        <li><b>Ігнорувати</b> — додає правило виключення цього файлу або розширення з майбутньої синхронізації.</li>
                    </ul>
                </li>
                <br/>
                <li><b>Захист від застарілих планів</b><br/>
                Якщо між створенням плану та його виконанням файли на ПК чи диску було змінено/видалено — SyncForge автоматично перевірить актуальність перед записом і оновить план, унеможливлюючи перезапис застарілими даними!</li>
            </ul>
            """
        )

        c_layout.addStretch()
        scroll.setWidget(container)
        layout.addWidget(scroll)
