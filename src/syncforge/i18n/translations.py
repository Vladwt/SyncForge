CURRENT_LANG = "uk"  # Ukrainian default


def set_language(lang_code: str):
    global CURRENT_LANG
    if lang_code in TRANSLATIONS:
        CURRENT_LANG = lang_code


def tr(key: str) -> str:
    """Translates key to current language with fallback to English or key itself."""
    return TRANSLATIONS.get(CURRENT_LANG, {}).get(key, TRANSLATIONS["en"].get(key, key))


def format_bytes(size_bytes: int) -> str:
    """Format bytes into clean human-readable units (B, KB, MB, GB, TB)."""
    if size_bytes < 0:
        return "0 B"
    for unit in ['B', 'KB', 'MB', 'GB', 'TB', 'PB']:
        if size_bytes < 1024.0 or unit == 'PB':
            if unit in ('B', 'KB'):
                return f"{int(size_bytes)} {unit}"
            return f"{size_bytes:.2f} {unit}"
        size_bytes /= 1024.0
    return f"{size_bytes:.2f} TB"
